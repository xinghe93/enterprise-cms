-- 004：员工状态变更版本号（PR #39 审查 P1：独立于 updated_at 的单调递增撤销版本）。
--
-- 背景：此前会话撤销版本取自 sys_user.updated_at 的 UTC 毫秒。
-- 该列随资料更新（改名/调岗）也会抬升，且同一毫秒内的两次状态变更无法取得
-- 独立递增的版本，导致「重复启用撤销正常会话」与「重复版本跳过撤销」两类缺陷。
--
-- 新列语义：
--   * 仅在状态真正发生变化（0↔1）时由 updateStatus 原子 +1，资料更新不触碰；
--   * 启停事务以该值作为会话撤销版本：停用在提交后撤销，重新启用在提交前撤销，
--     确保前序撤销完成后才允许重新启用（账号启用状态下不存在任何未撤销的旧会话）；
--   * DEFAULT 0 表示「从未发生状态变更」，对应该用户没有任何待撤销记录。
--
-- 存量数据初始化说明：本系统上线前的会话撤销以 updated_at 为版本（已废弃），
-- 存量用户的 status_version 统一为 0。语义上「0 = 从未有需要撤销的状态变更」：
--   * 存量停用账号本就无人持有会话，无需补偿撤销；
--   * 存量启用账号下次真正的 0↔1 变更会把版本抬到 1，高于 Redis 中任何旧记录
--     （旧记录键为 cms:auth:revoked-version:*，与新版本体系共用键空间但按用户隔离），
--     届时会执行一次幂等撤销，多余但无害；
--   * 旧 updated_at 毫秒值远大于 1，若 Redis 中残留旧体系记录会掩盖新版本——
--     迁移时请一并执行：DEL cms:auth:revoked-version:*（键不设 TTL，需手工清理）。
ALTER TABLE sys_user
    ADD COLUMN status_version BIGINT UNSIGNED NOT NULL DEFAULT 0
    COMMENT '状态变更版本：每次启停 +1，作为会话撤销的幂等版本' AFTER updated_at;
